export function localizeError(message: string, english: boolean) {
  if (!english) return message;
  const status = /^AI 请求失败（(\d+)），/.exec(message)?.[1];
  if (status) return `The AI request failed (${status}). Check the service URL, the model, and API compatibility.`;
  return Object.hasOwn(ERROR_MESSAGES, message) ? ERROR_MESSAGES[message] : message;
}
